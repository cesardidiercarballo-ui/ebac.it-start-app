# operadores aritmeticos 
a = 10
b = 5

suma = a + b
resta = a - b
multiplicacion = a * b
division = a / b
potencia = a ** b
modulo = a % b


# operadores de comparacion
print(" 'a' es igual a 'b':", a == b) # false
print(" 'a' es diferente a 'b':", a != b) # true
print(" 'a' es mayor que 'b':", a > b) # true
print(" 'a' es mayor o igual que 'b':", a >= b) # true
print(" 'a' es menor que 'b':", a < b) # false
print(" 'a' es menor o igual que 'b':", a <= b) # false
#operadores  logicos 
x = 8
y = 5
print("x es mayor que y and x es menor que y:", x > y and x < 2) # false
print("x es mayor que y or x es menor que y:", x > y or x < 2) # true
print("not x es mayor que y:", not x == 8) # false